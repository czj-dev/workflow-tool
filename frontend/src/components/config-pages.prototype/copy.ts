/** 极简插值：把 "{{n}}" 换成实参（原型不值得引入 i18next 的临时命名空间）。 */
function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{\{\s*(\w+)\s*\}\}/g, (m, k: string) => (k in values ? String(values[k]) : m));
}

export type CopyBag = Copy & {
  fill: (key: keyof Copy, values: Record<string, string | number>) => string;
};

export function useCopy(): CopyBag {
  const { i18n } = useTranslation();
  const lang = i18n.language.startsWith("zh") ? "zh" : "en";
  // 按语言记忆：返回稳定引用，才能安全地放进 useMemo 依赖
  return useMemo(() => {
    const c = lang === "zh" ? zh : en;
    return { ...c, fill: (key: keyof Copy, values: Record<string, string | number>) => fill(c[key], values) };
  }, [lang]);
}
